"""'Nobody steering vs comma's model' montage (4:5, 1080x1350) from the steering-pull test.

Per drive, the same 3 deg/s steering pull for 5 s, two rollouts inside comma's world model:
  top     nobody steering (the `straight` policy: only the pull acts)
  bottom  comma's driving model (the distillation teacher) at the wheel
Each panel: the generated narrow-camera frames (5 Hz, flow-interpolated to 30 fps), faint dots where the human drove
(placed at the car's true pose), and a live counter of how far the car is off the human's course (physics, metres,
lateral, from measure_forgiveness.py physics_offset_m).

  python make_offroad.py OUT.mp4 FRAMES_DIR results_pull_fixed.jsonl forgiveness_pull.jsonl SEG:START:KICK ...
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import cv2
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from render import (AMBER, BG, FPS_OUT, FPS_SRC, GREEN, INK, MUTED, RED, Canvas, Rollout, Writer, ego_to_device,  # noqa: E402
                    project, upscale)

W, H = 1080, 1350
PW, PH = 1080, 590  # panel: 2:1 frame upscaled to 1180 wide, cropped 50 px each side
HEADER = 112
GAP = 14


def off_at(arr: np.ndarray, t: float) -> float:
    return float(np.interp(t, np.arange(len(arr)), arr))


def human_dots(cam: np.ndarray, r: Rollout, t: float, crop: int) -> np.ndarray:
    scale = (cam.shape[1] + 2 * crop) / 256.0
    ss = 2
    layer = np.zeros((cam.shape[0] * ss, cam.shape[1] * ss, 4), np.uint8)
    hp = r.human_ahead(t)
    hp = hp[(hp[:, 0] > 4.0) & (hp[:, 0] < 70)]
    if len(hp) > 1:
        pix = project(ego_to_device(hp))
        for k, p in enumerate(pix[::2]):
            if not np.isfinite(p).all():
                continue
            x, y = (p[0] * scale - crop) * ss, p[1] * scale * ss
            if -20 < x < cam.shape[1] * ss + 20:
                rad = max(3, int((7 - k * 0.35) * ss))
                cv2.circle(layer, (int(x), int(y)), rad, (*INK, 200), -1, cv2.LINE_AA)
    layer = cv2.resize(layer, (cam.shape[1], cam.shape[0]), interpolation=cv2.INTER_AREA)
    a = layer[..., 3:4].astype(np.float32) / 255.0
    return (cam.astype(np.float32) * (1 - a) + layer[..., :3].astype(np.float32) * a).astype(np.uint8)


def panel(cv_: Canvas, r: Rollout, off: np.ndarray, t: float, y: int, label: str, dot) -> None:
    big = upscale(r.image(t)[..., :3], PW + 100)
    crop = 50
    cam = np.ascontiguousarray(big[:PH, crop:crop + PW]) if big.shape[0] >= PH else cv2.resize(big[:, crop:crop + PW], (PW, PH))
    cam = human_dots(cam, r, t, crop)
    cv_.paste(cam, (0, y))
    # label chip
    cv_.rrect((22, y + 20, 22 + 30 + len(label) * 19, y + 70), 12, fill=(0, 0, 0, 165))
    cv_.d.ellipse((38, y + 36, 56, y + 54), fill=dot)
    cv_.text((68, y + 27), label, 30, INK)
    # off-course counter
    v = off_at(off, t)
    col = GREEN if v < 1.8 else AMBER if v < 3.6 else RED
    cv_.rrect((W - 300, y + 20, W - 22, y + 128), 14, fill=(0, 0, 0, 165))
    cv_.text((W - 40, y + 24), f"{v:.1f} m", 62, col, anchor="ra")
    cv_.text((W - 40, y + 96), "off course", 22, MUTED, bold=False, anchor="ra")


def main() -> None:
    out, frames_dir, res_p, meas_p = sys.argv[1], Path(sys.argv[2]), sys.argv[3], sys.argv[4]
    picks = [s.split(":") for s in sys.argv[5:]]
    rows = {(r["segment"], r["start"], r["policy"], r["kick"]): r for r in map(json.loads, open(res_p))}
    meas = {(m["segment"], m["start"], m["policy"], m["kick"]): m for m in map(json.loads, open(meas_p))}
    wr = Writer(Path(out), W, H)
    prev = None
    for seg, start, kick in picks:
        st = int(start)
        pair = []
        for pol in ("straight", "teacher"):
            key = (seg, st, pol, kick)
            r = Rollout(rows[key], frames_dir / f"{seg}_{st}_{pol}_{kick}.npz")
            off = np.abs(np.asarray(meas[key]["physics_offset_m"], float))
            pair.append((r, off))
        side = "right" if rows[(seg, st, "straight", kick)]["pull_dps"] > 0 else "left"
        n = min(pair[0][0].n, pair[1][0].n) - 1
        steps = int(round(n / FPS_SRC * FPS_OUT))
        last = None
        for i in range(steps + 1):
            t = i * n / steps
            cv_ = Canvas(W, H, BG)
            cv_.text((W // 2, 22), f"steering pulled 3°/s to the {side}", 40, INK, anchor="mt")
            cv_.text((W // 2, 74), "every frame generated by comma's world model", 24, MUTED, bold=False, anchor="mt")
            panel(cv_, pair[0][0], pair[0][1], t, HEADER, "nobody steering", RED)
            panel(cv_, pair[1][0], pair[1][1], t, HEADER + PH + GAP, "comma's model", GREEN)
            cv_.text((W // 2, H - 18), "dots: where the human drove  ·  5 Hz frames, interpolated to 30 fps", 20, MUTED,
                     bold=False, anchor="ms")
            f = cv_.array()
            if prev is not None and i < 8:
                a = (i + 1) / 9
                f = (prev.astype(np.float32) * (1 - a) + f.astype(np.float32) * a).astype(np.uint8)
            wr.write(f)
            last = f
        wr.hold(last, 0.9)
        prev = last
    wr.close()
    print(f"wrote {out}: {wr.n} frames, {wr.n / FPS_OUT:.1f} s")


if __name__ == "__main__":
    main()
